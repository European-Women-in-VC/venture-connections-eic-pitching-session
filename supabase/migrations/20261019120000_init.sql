-- EIC Pitching Session — speakers, investor submissions, 1:1 meeting requests.
-- Mirrors the Airtable base ("EIC - Speakers", "EIC - Investor Submissions", "EIC - 1:1 Meetings").
-- Access: only the server (Vercel, secret key) reads and writes; RLS blocks the public API keys.

-- ---------------------------------------------------------------------------
-- Types
-- ---------------------------------------------------------------------------
create type public.speaker_state as enum ('open', 'paused', 'unavailable', 'closed');

create type public.submission_status as enum ('todo', 'in_progress', 'done', 'confirmed', 'test');

create type public.request_status as enum (
  'new_request',
  'needs_review',
  'waitlisted',
  'hold_awaiting_speaker',
  'accepted_scheduling',
  'scheduled_confirmed',
  'declined',
  'cancelled',
  'expired'
);

create type public.closure_reason as enum (
  'speaker_declined',
  'speaker_unavailable',
  'investor_cancelled',
  'organizer_cancelled',
  'no_response_expired',
  'duplicate',
  'other'
);

-- Statuses that take one of a speaker's places (Airtable "Capacity Units" = 1)
create function public.request_takes_place(s public.request_status)
returns boolean
language sql
immutable
set search_path = ''
as $$
  select s in ('new_request', 'needs_review', 'hold_awaiting_speaker', 'accepted_scheduling', 'scheduled_confirmed');
$$;

create function public.set_updated_at()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

-- ---------------------------------------------------------------------------
-- Tables
-- ---------------------------------------------------------------------------
create table public.speakers (
  id uuid primary key default gen_random_uuid(),
  slug text not null unique check (slug ~ '^[a-z0-9]+(-[a-z0-9]+)*$'), -- must equal the Webflow CMS slug
  name text not null,
  company text not null,
  capacity integer not null default 4 check (capacity >= 0),
  availability public.speaker_state not null default 'open',
  assignee text,
  notes text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.submissions (
  id uuid primary key default gen_random_uuid(),
  booking_id text unique, -- generated by the page per visit; makes retries idempotent
  email text not null,
  first_name text,
  last_name text,
  company text,
  linkedin text,
  speaker_slugs text[] not null default '{}', -- everything the investor picked, in pick order
  status public.submission_status not null default 'todo',
  assignee text,
  notes text,
  meta jsonb not null default '{}', -- raw extra form fields, user agent etc.
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.meeting_requests (
  id uuid primary key default gen_random_uuid(),
  request_number bigint generated always as identity unique,
  submission_id uuid not null references public.submissions (id) on delete cascade,
  speaker_id uuid not null references public.speakers (id) on delete restrict,
  status public.request_status not null default 'new_request',
  preference_rank smallint check (preference_rank > 0),
  hold_until timestamptz,
  speaker_response_at timestamptz,
  scheduled_start timestamptz,
  scheduled_end timestamptz,
  confirmation_sent_at timestamptz,
  closure_reason public.closure_reason,
  assignee text,
  internal_notes text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (submission_id, speaker_id)
);

create index meeting_requests_speaker_id_idx on public.meeting_requests (speaker_id);
create index submissions_email_idx on public.submissions (lower(email));

create trigger speakers_updated_at before update on public.speakers
  for each row execute function public.set_updated_at();
create trigger submissions_updated_at before update on public.submissions
  for each row execute function public.set_updated_at();
create trigger meeting_requests_updated_at before update on public.meeting_requests
  for each row execute function public.set_updated_at();

-- ---------------------------------------------------------------------------
-- Availability (Airtable: Capacity Used / Available Places / Capacity Status)
-- ---------------------------------------------------------------------------
create view public.speaker_availability
with (security_invoker = true)
as
select
  sp.id,
  sp.slug,
  sp.name,
  sp.company,
  sp.capacity,
  sp.availability,
  c.used,
  c.confirmed,
  c.waitlisted,
  greatest(sp.capacity - c.used, 0) as remaining,
  case when sp.availability = 'open' then greatest(sp.capacity - c.used, 0) else 0 end as available,
  case
    when c.used > sp.capacity then 'over_capacity'
    when sp.availability <> 'open' then sp.availability::text
    when sp.capacity - c.used <= 0 then 'full'
    else 'available'
  end as status
from public.speakers sp
cross join lateral (
  select
    count(*) filter (where public.request_takes_place(mr.status))::integer as used,
    count(*) filter (where mr.status in ('accepted_scheduling', 'scheduled_confirmed'))::integer as confirmed,
    count(*) filter (where mr.status = 'waitlisted')::integer as waitlisted
  from public.meeting_requests mr
  where mr.speaker_id = sp.id
) c;

-- ---------------------------------------------------------------------------
-- Booking: check places and save in one transaction
-- ---------------------------------------------------------------------------
-- Returns one of:
--   { "ok": true,  "submission_id": "…", "unknown": [slugs not in speakers] }
--   { "ok": true,  "submission_id": "…", "duplicate": true }      (same booking_id sent again)
--   { "ok": false, "error": "unavailable", "unavailable": [slugs] } (nothing saved)
create function public.book_meetings(
  p_booking_id text,
  p_email text,
  p_first_name text,
  p_last_name text,
  p_speaker_slugs text[],
  p_company text default null,
  p_linkedin text default null,
  p_meta jsonb default '{}'
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_slugs text[];
  v_submission_id uuid;
  v_unavailable text[];
  v_unknown text[];
begin
  -- unique, trimmed slugs in pick order
  select coalesce(array_agg(slug order by first_pos), '{}')
    into v_slugs
    from (
      select trim(s) as slug, min(pos) as first_pos
      from unnest(p_speaker_slugs) with ordinality as u(s, pos)
      where trim(coalesce(s, '')) <> ''
      group by trim(s)
    ) d;

  if p_email is null or p_email !~* '^[^@\s]+@[^@\s]+\.[^@\s]+$' then
    raise exception 'invalid_email' using errcode = '22023';
  end if;
  if cardinality(v_slugs) = 0 or cardinality(v_slugs) > 4 then
    raise exception 'invalid_selection' using errcode = '22023';
  end if;

  -- same visit submitted twice (double click, retry) → return the first result
  if p_booking_id is not null then
    select id into v_submission_id from public.submissions where booking_id = p_booking_id;
    if found then
      return jsonb_build_object('ok', true, 'submission_id', v_submission_id, 'duplicate', true);
    end if;
  end if;

  -- lock the chosen speakers (fixed order → no deadlocks); parallel bookings for them wait here
  perform 1 from public.speakers where slug = any (v_slugs) order by id for update;

  select coalesce(array_agg(sa.slug), '{}')
    into v_unavailable
    from public.speaker_availability sa
    where sa.slug = any (v_slugs) and sa.status <> 'available';

  if cardinality(v_unavailable) > 0 then
    return jsonb_build_object('ok', false, 'error', 'unavailable', 'unavailable', to_jsonb(v_unavailable));
  end if;

  select coalesce(array_agg(s), '{}')
    into v_unknown
    from unnest(v_slugs) s
    where not exists (select 1 from public.speakers sp where sp.slug = s);

  insert into public.submissions (booking_id, email, first_name, last_name, company, linkedin, speaker_slugs, meta)
  values (
    p_booking_id,
    lower(trim(p_email)),
    nullif(trim(p_first_name), ''),
    nullif(trim(p_last_name), ''),
    nullif(trim(p_company), ''),
    nullif(trim(p_linkedin), ''),
    v_slugs,
    coalesce(p_meta, '{}')
  )
  returning id into v_submission_id;

  insert into public.meeting_requests (submission_id, speaker_id, preference_rank)
  select v_submission_id, sp.id, u.pos::smallint
  from unnest(v_slugs) with ordinality as u(slug, pos)
  join public.speakers sp on sp.slug = u.slug;

  return jsonb_build_object('ok', true, 'submission_id', v_submission_id, 'unknown', to_jsonb(v_unknown));
exception
  when unique_violation then
    -- two identical requests at the same moment: the other one won
    select id into v_submission_id from public.submissions where booking_id = p_booking_id;
    return jsonb_build_object('ok', true, 'submission_id', v_submission_id, 'duplicate', true);
end;
$$;

-- ---------------------------------------------------------------------------
-- Access: server only
-- ---------------------------------------------------------------------------
alter table public.speakers enable row level security;
alter table public.submissions enable row level security;
alter table public.meeting_requests enable row level security;
-- no policies: anon/authenticated keys can't read or write; the secret key bypasses RLS

revoke all on public.speaker_availability from anon, authenticated;
revoke execute on function public.book_meetings(text, text, text, text, text[], text, text, jsonb) from public, anon, authenticated;
grant execute on function public.book_meetings(text, text, text, text, text[], text, text, jsonb) to service_role;
